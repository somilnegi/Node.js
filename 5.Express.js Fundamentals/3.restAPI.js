// API stands for Application Programming Interface. It is a way for different software applications to communicate with each other.

// REST or Representational State Transfer is a style of API that uses HTTP methods like GET, POST, PUT, and DELETE to perform operations on resources.
// It is a way for applications to exchange data over the web.
// It is an architectural style for building web services.

// Key principles of a REST API:

// 1. Stateless: Each request should have no state associated with it. This means that the server should not store any information about the client between requests because the server scales up and down and this can cause issues. This promotes scalability, flexibility, security, and simplicity in building web services.

// 2.Client-Server Architecture: The client and server are separate entities. The client makes requests to the server, and the server responds with the requested data.

// 3.Uniform Interface: REST APIs use standard HTTP methods and status codes to define the behavior of the API. For example, GET is used to retrieve data, POST is used to create new resources, PUT is used to update existing resources, and DELETE is used to remove resources.

// 4. Cacheable: The server should return the same response for the same request. This is important for performance and scalability.

// 5. Layered Architecture: REST APIs are often built using a layered architecture, where the server handles the business logic and the client handles the presentation layer.


